"""
Tests for the real-catalogue path: data/ingest_real_data.py and
src/real_data_validation.py.

These tests are skipped, not failed, when `data/real_*.db` is absent: those
files come from public mirrors (Open Food Facts, Open Prices, WDC Products) and
are regenerated by

    python data/ingest_real_data.py --source all

The point of the module they test is that the EXISTING harnesses load a
catalogue nobody in this repository wrote, without a single change.
"""
import os
import sqlite3
import sys

import pytest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

from attribute_algebra import CONFLICT, canonical_form, fold_all
from benchmark_cases import load_snapshot
from real_data_validation import (
    build_real_cases,
    report_algebra,
    report_catalog,
    report_groups,
    report_price_dispersion,
)


#: Prefer a full catalogue when one has been ingested; otherwise fall back to the
#: trimmed fixture committed under tests/fixtures. The fixtures exist so that CI
#: exercises the real-catalogue code path at all -- with only git-ignored
#: databases, every test here would skip and the path would rot unnoticed.
def _candidate(name: str) -> str:
    full = os.path.join(ROOT, "data", f"real_{name}.db")
    if os.path.exists(full):
        return full
    return os.path.join(ROOT, "tests", "fixtures", f"real_{name}_fixture.db")


REAL_DBS = {name: _candidate(name) for name in ("off", "prices", "wdc")}
AVAILABLE = {name: path for name, path in REAL_DBS.items() if os.path.exists(path)}


def _any_db() -> str:
    if not AVAILABLE:
        pytest.skip("no real catalogue available: neither data/real_*.db nor "
                    "tests/fixtures/*_fixture.db")
    return sorted(AVAILABLE.values())[0]


def test_a_real_catalogue_is_always_available_to_these_tests():
    """Guard against the guard.

    Every test in this file skips when no catalogue is found, and a skip is
    easy to miss in a green run. The fixtures are committed precisely so this
    cannot happen silently: if a checkout has none of them, that is a defect in
    the repository, not a reason to pass quietly.
    """
    missing = sorted(name for name, path in REAL_DBS.items()
                     if not os.path.exists(path))
    assert not missing, (
        f"no catalogue for {missing}: tests/fixtures must be committed "
        f"(regenerate with data/make_fixtures.py)")


@pytest.mark.parametrize("name,path", sorted(REAL_DBS.items()))
def test_ingested_catalogue_has_the_project_schema(name, path):
    if not os.path.exists(path):
        pytest.skip(f"no catalogue for {name}: neither data/real_{name}.db nor "
                    f"tests/fixtures/real_{name}_fixture.db")
    conn = sqlite3.connect(path)
    try:
        tables = {r[0] for r in conn.execute(
            "SELECT name FROM sqlite_master WHERE type='table'")}
        assert {"merchants", "products", "product_eav_meta", "ingest_meta"} <= tables
        products = conn.execute("SELECT COUNT(*) FROM products").fetchone()[0]
        eav = conn.execute("SELECT COUNT(*) FROM product_eav_meta").fetchone()[0]
        assert products > 0 and eav > 0
        orphans = conn.execute(
            "SELECT COUNT(*) FROM product_eav_meta m LEFT JOIN products p "
            "ON p.id = m.product_id WHERE p.id IS NULL").fetchone()[0]
        assert orphans == 0
        # Provenance is part of the schema: without it a real catalogue is
        # indistinguishable from a generated one.
        for key in ("source", "license"):
            assert conn.execute("SELECT value FROM ingest_meta WHERE key = ?",
                                (key,)).fetchone(), f"ingest_meta.{key} missing"
    finally:
        conn.close()


def test_load_snapshot_reads_a_real_catalogue_unchanged():
    snap = load_snapshot(_any_db())
    assert snap.products, "the snapshot loaded no products"
    assert snap.concepts, "concept discovery found nothing in a real catalogue"
    assert snap.attrs, "no EAV attributes were loaded"


def test_validation_sections_run_on_real_data():
    snap = load_snapshot(_any_db())
    catalog = report_catalog(snap)
    assert catalog["products"] > 0 and catalog["eav_keys"] > 0

    algebra = report_algebra(snap)
    assert algebra["values_examined"] > 0
    assert 0.0 <= algebra["canonicalisable_pct"] <= 100.0

    groups = report_groups(snap)
    assert "group_key" in groups
    dispersion = report_price_dispersion(snap)
    assert "groups_with_several_prices" in dispersion


def test_algebra_is_idempotent_on_real_surface_values():
    """Whatever the catalogue writes, canonicalisation must be a projection."""
    snap = load_snapshot(_any_db())
    seen = 0
    for per in snap.attrs.values():
        for values in per.values():
            for value in values[:4]:
                once = canonical_form(value)
                if once is None:
                    continue
                assert canonical_form(str(once)) == once
                seen += 1
                if seen >= 300:
                    return
    assert seen > 0, "no canonicalisable value found in a real catalogue"


def test_real_case_builder_produces_oracles_or_skips_honestly():
    snap = load_snapshot(_any_db())
    cases = build_real_cases(snap, n=12, seed=1)
    if not any(c.case_type == "direct_price" for c in cases):
        pytest.skip("this catalogue carries no prices; price families are skipped")
    for case in cases[:5]:
        assert case.query and case.oracle.case_id == case.case_id
        for name, prices in case.oracle.expected_prices.items():
            assert prices, f"{name} anchored to no price"
            assert all(float(p) > 0 for p in prices)


def test_mass_and_volume_units_do_not_collapse():
    """Verify distinct metric scale units (0.5 g vs 0.5 mg) never collapse."""
    assert canonical_form("0.5 g") != canonical_form("0.5 mg")
    assert fold_all(["0.5 g", "0.5 mg"]) is CONFLICT
